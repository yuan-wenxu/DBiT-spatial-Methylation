# methylated C positions in BARCODE_INSERT_LEFT, using 0-based coordinates
BARCODE_METHYLATED_C_POSITIONS=${BARCODE_METHYLATED_C_POSITIONS:-3,6,10}
BARCODE_LINKER_EDIT_DISTANCE=${BARCODE_LINKER_EDIT_DISTANCE:-1}
