BARCODE_PARTITION=${BARCODE_PARTITION:-}
BARCODE_MEM=${BARCODE_MEM:-64G}
BARCODE_TIME=${BARCODE_TIME:-24:00:00}

ALIGN_NAME=${ALIGN_NAME:-align}
